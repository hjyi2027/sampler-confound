DOC_SHORT = {
    "top_p": "nucleus sampling", "top_k": "top-$k$ filtering",
    "min_p": "minimum-probability filter", "typical_p": "typical-$p$ sampling",
    "mirostat": "target perplexity", "repetition_penalty": "penalty above 1.0",
    "frequency_penalty": "penalty by frequency", "presence_penalty": "penalty by presence",
}


def table_params(D: dict) -> str:
    lines = []
    for p in P8:
        c = D["by_param"][p]
        n = sum(c.values())
        acc = sum(1 for (m, q), cell in D["cls"].items() if q == p and cell["accepted"] == "yes")
        inert = str(c["no"]) if c["no"] == 0 else r"\textbf{" + str(c["no"]) + "}"
        lines.append(f"{TEX_PARAM[p]} & {DOC_SHORT[p]} & {acc}/{n} & {c['yes']} & {c['mixed']} & "
                     f"{inert} & {c['undetermined']} \\\\")
    tot = Counter()
    for p in P8:
        tot.update(D["by_param"][p])
    lines.append(r"\midrule")
    lines.append(f"all eight & & 144/144 & {tot['yes']} & {tot['mixed']} & {tot['no']} & {tot['undetermined']} \\\\")
    return "\n".join(lines) + "\n"


def table_undoc(D: dict) -> str:
    rows = _load(RUNS / "matrix" / "undocumented.json")["rows"]
    out = {}
    for p in ("use_beam_search", "skip_special_tokens", "ignore_eos", "best_of"):
        c = Counter()
        for r in rows:
            v = r[p]["verdict"]
            c["ignored" if v == "ignored" else "honoured" if v == "honoured" else
              "error" if v.startswith("error") else "rejected" if v == "rejected" else "undetermined"] += 1
        out[p] = (c, len(rows))
    def cell(c):
        parts = []
        if c["honoured"]:
            parts.append(r"\textbf{honoured on " + str(c["honoured"]) + "}")
        if c["ignored"]:
            parts.append(r"\textbf{no effect on " + str(c["ignored"]) + "}")
        if c["undetermined"]:
            parts.append(f"undetermined on {c['undetermined']}")
        if c["error"]:
            parts.append(f"HTTP 500 on {c['error']}")
        return ", ".join(parts)
    test = {"use_beam_search": "10 calls at $T=1.0$ agree",
            "skip_special_tokens": "end-of-turn marker in text",
            "ignore_eos": "one-word reply runs to the cap",
            "best_of": "none observable from outside"}
    lines = []
    for p in ("use_beam_search", "skip_special_tokens", "ignore_eos", "best_of"):
        c, n = out[p]
        rej = c["rejected"]
        lines.append(f"{tt(p)} & {test[p]} & {n - rej}/{n} & {cell(c)} \\\\")
    return "\n".join(lines) + "\n"


def table_settings() -> str:
    """The two arms of every contrast, as values of the row's parameter. Every
    arm except the control's tight arm is at temperature 1.0."""
    lines = []
    for name, tight, open_, primary in CONTRASTS:
        def fmt(s):
            kv = {k: v for k, v in s.items() if k != "temperature"}
            if name == "mirostat":
                return (f"target {kv['mirostat_target']}, rate {kv['mirostat_lr']}"
                        if kv else "off")
            return ", ".join(str(v) for v in kv.values())
        if name == "temperature":
            lines.append(r"control & $T=0$ & $T=1.0$, no truncation & power reference \\")
            continue
        role = "TV, two-sided" if primary == "tv" else r"$\Delta H$, one-sided"
        lines.append(f"{TEX_PARAM.get(name, tex(name))} & {fmt(tight)} & {fmt(open_)} & {role} \\\\")
    return "\n".join(lines) + "\n"


def table_models(D: dict) -> str:
    lines = []
    for r in D["models"]:
        price = r["usd_out_per_1m"]
        col = r["collected"]
        win = col["from"][:10] + (r"--" + col["to"][5:10] if col["to"][:10] != col["from"][:10] else "")
        pin = PRICES.get(r["model"], (float("nan"),))[0]
        n_arm = r.get("n_per_arm")
        n_arm = "10/40$^{a}$" if isinstance(n_arm, str) and "-" in n_arm else n_arm
        lines.append(f"{tt(r['model'])} & "
                     + (f"{pin:.2f} & {price:.2f}" if price == price else r"\multicolumn{2}{c}{unpriced}")
                     + f" & {n_arm} & {win} \\\\")
    return "\n".join(lines) + "\n"


SYM = {"distinguishable": "+", "no effect seen": r"\textminus", "mixed": r"$\pm$",
       "underpowered": "?", "insufficient": "?", "transport": "err", "rejected": "rej", "": "--"}


def _fmt_p(p) -> str:
    if p is None or p != p:
        return "--"
    if p < 0.001:
        return r"$<$0.001"
    return f"{p:.3f}"


def table_cells_nonhonoured(D: dict) -> str:
    """Every cell that is not a clean effect, with the numbers behind it."""
    sel, cls, adj = D["sel"], D["cls"], D["sens"]["grid_adjusted"]
    order = {r["model"]: i for i, r in enumerate(D["models"])}
    keys = sorted((k for k in sel if k[1] in P8 and cls[k]["honoured"] != "yes"),
                  key=lambda k: (P8.index(k[1]), order[k[0]]))
    lines = []
    for k in keys:
        a = sel[k]["a"]
        forced = a.get("verdict_forced", "")
        power = a.get("stratified_control_power")
        lines.append(
            f"{tt(k[0])} & {TEX_PARAM[k[1]]} & {sel[k]['n']} & {a.get('stratified_prompts', 0)} & "
            f"{_fmt_p(a.get('stratified_p'))} & {_fmt_p(a.get('stratified_p_holm'))} & "
            f"{_fmt_p(adj.get(('T',) + k))} & "
            f"{'--' if power is None or power != power else f'{power:.2f}'} & "
            f"{SYM.get(forced, forced) if k[1] in PENALTIES else ''} & "
            f"{ {'no': 'inert', 'mixed': 'mixed', 'undetermined': 'no verdict'}[cls[k]['honoured']] } \\\\")
    return "\n".join(lines) + "\n"


def table_determinism(D: dict) -> str:
    seed, conc, m5 = D["seed"], D["conc"], D["math500"]
    lines = []
    order = sorted(seed["per_model"], key=lambda m: -seed["per_model"][m]["no_seed"])
    rows = determinism_rows()
    for m in order:
        cs = [r for (mm, p), r in rows.items() if mm == m]
        ns = np.mean([r["conditions"]["no_seed"]["content"][0] for r in cs])
        s0 = np.mean([r["conditions"]["seed_0"]["content"][0] for r in cs])
        s1 = np.mean([r["conditions"]["seed_1"]["content"][0] for r in cs])
        v = conc["summary"][m]
        mm5 = m5.get(m, (float("nan"), 0))
        lines.append(f"{tt(m)} & {ns:.2f} & {s0:.2f} & {s1:.2f} & {int(round(mm5[0] * 10))}/10 & "
                     f"{v['concurrent_pairwise']:.2f} & {v['sequential_pairwise']:.2f} & "
                     f"{v['concurrent_full_prompts']}/{v['prompts']} & {v['sequential_full_prompts']}/{v['prompts']} \\\\")
    return "\n".join(lines) + "\n"


def table_control(D: dict) -> str:
    """Per model and free-text prompt: power of the positive control."""
    latest = D["control"]["latest"]
    lines = []
    for r in D["models"]:
        m = r["model"]
        cells = []
        for pid in PROMPTS:
            mp = latest.get((m, pid))
            if not mp or mp.get("control_power") is None or mp.get("control_power") != mp.get("control_power"):
                cells.append("--")
            else:
                pw = mp["control_power"]
                cells.append((r"\textbf{" if pw >= 0.8 else "") + f"{pw:.2f}" + ("}" if pw >= 0.8 else ""))
        lines.append(f"{tt(m)} & " + " & ".join(cells) + r" \\")
    return "\n".join(lines) + "\n"


def write_csv(D: dict, dest: Path) -> None:
    sel, cls, adj = D["sel"], D["cls"], D["sens"]["grid_adjusted"]
    with dest.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["model", "parameter", "n_per_arm", "source_file", "free_text_verdict",
                    "forced_verdict", "stratified_p", "p_holm_within_model", "p_holm_grid",
                    "forced_p", "control_power", "prompts_pooled", "honoured", "label"])
        for r in D["models"]:
            for p in P8:
                k = (r["model"], p)
                a = sel[k]["a"]
                w.writerow([k[0], p, sel[k]["n"], sel[k]["file"], a["verdict"],
                            a.get("verdict_forced", ""), a.get("stratified_p"),
                            a.get("stratified_p_holm"), adj.get(("T",) + k),
                            sel[k]["forced_p"] if p in PENALTIES else "",
                            a.get("stratified_control_power"), a.get("stratified_prompts"),
                            cls[k]["honoured"], cls[k]["label"]])


