def holm(ps: dict) -> dict:
    items = sorted(((k, p) for k, p in ps.items() if p == p), key=lambda kv: kv[1])
    m, run, out = len(items), 0.0, {}
    for i, (k, p) in enumerate(items):
        run = max(run, min(1.0, (m - i) * p))
        out[k] = run
    return out


def clopper_pearson_upper(k: int, n: int, level: float = 0.95) -> float:
    """One-sided upper confidence bound for a binomial proportion."""
    from scipy.stats import beta
    return 1.0 if k >= n else float(beta.ppf(level, k + 1, n - k))


def sensitivity(sel: dict, cls: dict) -> dict:
    """What changes under (a) one Holm correction over every test in the grid
    and (b) a stricter rule for calling a cell inert (unadjusted p >= 0.05)."""
    free = {k: v["a"].get("stratified_p", float("nan")) for k, v in sel.items() if k[1] in P8}
    free = {k: (float(p) if p is not None else float("nan")) for k, p in free.items()}
    forced = {("F",) + k: v["forced_p"] for k, v in sel.items() if k[1] in PENALTIES}
    family = {**{("T",) + k: p for k, p in free.items()}, **forced}
    adj = holm(family)
    n_tests = sum(1 for p in family.values() if p == p)
    lost = []
    for k in [k for k in sel if k[1] in P8]:
        c = cls[k]
        if c["honoured"] != "yes":
            continue
        a = sel[k]["a"]
        ok_free = a["verdict"] == "distinguishable" and adj.get(("T",) + k, 1.0) < 0.05
        ok_forced = k[1] in PENALTIES and a.get("verdict_forced") == "distinguishable" \
            and adj.get(("F",) + k, 1.0) < 0.05
        if not (ok_free or ok_forced):
            lost.append(k)
    strict = [k for k in sel if k[1] in P8 and cls[k]["honoured"] == "no"
              and not (sel[k]["a"].get("stratified_p", 1.0) >= 0.05)]
    return {"n_tests_grid": n_tests, "lost_under_grid_holm": sorted(lost),
            "inert_failing_strict_rule": sorted(strict), "grid_adjusted": adj}


def negative_control() -> dict:
    """Identical arms, same collection order as a real test; the current
    degeneracy rule is applied, as in paper_numbers.py."""
    dh = tv = n = 0
    files = sorted(MATRIX.glob("*.neg-n40.json")) + [RUNS / "negative_control.json"]
    for f in files:
        d = _load(f)
        if not d:
            continue
        ok = [r for r in d["results"] if r["status"] == "ok"
              and not (r["support_tight"] >= r["n_tight"] - 1 and r["support_open"] >= r["n_open"] - 1)]
        n += len(ok)
        dh += sum(r["dh_p"] < 0.05 for r in ok)
        tv += sum(r["tv_p"] < 0.05 for r in ok)
    return {"pairs": n, "dh_fp": dh, "tv_fp": tv,
            "dh_upper": clopper_pearson_upper(dh, n), "tv_upper": clopper_pearson_upper(tv, n)}


def determinism_rows() -> dict[tuple[str, str], dict]:
    files = [RUNS / "determinism.json"] + [f for f in sorted(MATRIX.glob("*det*.json"))
                                            if "sequential" not in f.name]
    out = {}
    for f in files:
        d = _load(f)
        for r in (d or {}).get("rows", []):
            out[(r["model"], r["prompt"])] = r
    return out


def seed_analysis(rows: dict) -> dict:
    """Does a fixed seed make temperature-0 output more reproducible?

    Per (model, prompt): the modal share of ten identical requests without a
    seed, with seed=0 and with seed=1. If the seed does nothing at T=0 the
    three conditions are exchangeable within a cell, so the test permutes which
    condition is called 'no seed' within each cell. Cells of a model that is
    byte-identical under every condition carry no information and are dropped.
    """
    cells = []
    for (m, p), r in rows.items():
        c = r["conditions"]
        if all(c[k].get("n") == 10 for k in ("no_seed", "seed_0", "seed_1")):
            cells.append((m, p, c["no_seed"]["content"][0], c["seed_0"]["content"][0],
                          c["seed_1"]["content"][0]))
    det = {m for m in {c[0] for c in cells}
           if all(min(c[2:]) == 1.0 for c in cells if c[0] == m)}
    X = np.array([c[2:] for c in cells if c[0] not in det])
    obs = float((X[:, 1:].mean(1) - X[:, 0]).mean())
    rng = np.random.default_rng(0)
    B = 100_000
    pick = rng.integers(0, 3, size=(B, len(X)))
    chosen = X[np.arange(len(X))[None, :], pick]
    stat = ((X.sum(1)[None, :] - chosen) / 2 - chosen).mean(1)
    p_two = (1 + int(np.sum(np.abs(stat) >= abs(obs) - 1e-12))) / (1 + B)
    p_one = (1 + int(np.sum(stat >= obs - 1e-12))) / (1 + B)
    ns = [c for c in cells if c[2] < 1.0]
    s0 = [c for c in cells if c[3] < 1.0]
    s1 = [c for c in cells if c[4] < 1.0]
    per_model = defaultdict(lambda: {"no_seed": [], "seeded": []})
    for c in cells:
        per_model[c[0]]["no_seed"].append(c[2])
        per_model[c[0]]["seeded"].append((c[3] + c[4]) / 2)
    return {
        "cells": len(cells), "cells_tested": int(len(X)), "deterministic_models": sorted(det),
        "mean_diff": obs, "p_two": p_two, "p_one": p_one,
        "noseed_nonrepro": len(ns), "rescued_by_seed": sum(max(c[3], c[4]) >= 1.0 for c in ns),
        "seed0_nonrepro": len(s0), "seed0_rescued_by_other": sum(max(c[2], c[4]) >= 1.0 for c in s0),
        "seed1_nonrepro": len(s1), "seed1_rescued_by_other": sum(max(c[2], c[3]) >= 1.0 for c in s1),
        "per_model": {m: {k: float(np.mean(v)) for k, v in d.items()} for m, d in per_model.items()},
        "per_cell": cells,
    }


def concurrency() -> dict:
    from scipy.stats import binomtest
    sq = _load(MATRIX / "determinism_sequential.json")
    rows = [r for r in sq["rows"] if r["sequential"]["n"] == 10 and r["concurrent"]["n"] == 10]
    diffs = [r["sequential"]["pairwise"] - r["concurrent"]["pairwise"] for r in rows]
    up, down = sum(d > 1e-12 for d in diffs), sum(d < -1e-12 for d in diffs)
    summ = sq["summary"]
    delta = {m: v["sequential_pairwise"] - v["concurrent_pairwise"] for m, v in summ.items()}
    return {
        "pairs": len(rows), "up": up, "down": down, "ties": len(rows) - up - down,
        "sign_p": binomtest(up, up + down, 0.5).pvalue,
        "mean_modal_seq": float(np.mean([r["sequential"]["modal"] for r in rows])),
        "mean_modal_conc": float(np.mean([r["concurrent"]["modal"] for r in rows])),
        "mean_pair_seq": float(np.mean([r["sequential"]["pairwise"] for r in rows])),
        "mean_pair_conc": float(np.mean([r["concurrent"]["pairwise"] for r in rows])),
        "rise10": sorted(m for m, d in delta.items() if d >= 0.10 - 1e-9),
        "fall10": sorted(m for m, d in delta.items() if d <= -0.10 + 1e-9),
        "delta": delta, "summary": summ, "deterministic": sq["deterministic_models"],
        "collected": sq["collected"],
    }


def math500(rows: dict) -> dict:
    out = {}
    for (m, p), r in rows.items():
        if p == "math500":
            c = r["conditions"]["no_seed"]
            out[m] = (c["content"][0], c["content"][1])
    return out


def control_coverage(sel: dict) -> dict:
    """Per-prompt positive control across the reports the verdicts came from."""
    used_files = {v["file"] for v in sel.values()}
    powered = total = 0
    seen = set()
    for f in ordered_distinguish_files():
        if f.name not in used_files:
            continue
        d = _load(f)
        for pid, by_model in (d or {}).get("positive_control_by_prompt", {}).items():
            if pid in FORCED_PROMPTS:
                continue
            for m, mp in by_model.items():
                seen.add((m, pid))
    # latest report wins per (model, prompt), as for the verdicts
    latest = {}
    for f in ordered_distinguish_files():
        if f.name not in used_files:
            continue
        d = _load(f)
        for pid, by_model in (d or {}).get("positive_control_by_prompt", {}).items():
            if pid in FORCED_PROMPTS:
                continue
            for m, mp in by_model.items():
                latest[(m, pid)] = mp
    total = len(latest)
    powered = sum(bool(mp.get("powered")) for mp in latest.values())
    return {"pairs": total, "powered": powered, "latest": latest}


def derive() -> dict:
    sel = load_cells()
    cls = classification()
    rows = determinism_rows()
    by_param = defaultdict(Counter)
    for (m, p), c in cls.items():
        by_param[p][c["honoured"]] += 1
    return {
        "sel": sel, "cls": cls, "by_param": by_param,
        "sens": sensitivity(sel, cls),
        "neg": negative_control(),
        "seed": seed_analysis(rows),
        "conc": concurrency(),
        "math500": math500(rows),
        "control": control_coverage(sel),
        "models": models_in_order(),
    }


