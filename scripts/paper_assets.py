def ordered_distinguish_files() -> list[Path]:
    """The legacy multi-prompt report first, then every per-model report
    thinnest first, exactly as collect() merges them, so a later file's
    aggregate for a (model, parameter) replaces an earlier one."""
    out = [RUNS / "distinguish_multiprompt.json"]
    files = []
    for f in MATRIX.glob("*.json"):
        name = f.name
        if name in ("determinism.json", "matrix.json", "determinism_sequential.json") \
                or ".neg-n" in name or name.endswith(".det.json"):
            continue
        m = re.match(r"(.+)\.dist-n(\d+)\.json$", name)
        model, n = (m.group(1), int(m.group(2))) if m else (name[:-5], 40)
        files.append((n, model, f))
    return out + [f for _, _, f in sorted(files)]


def forced_p(d: dict, model: str, param: str) -> float:
    """Raw p-value of the forced-repetition test for (model, param) in report d."""
    for r in d.get("results", []):
        if r["model"] == model and r["parameter"] == param and r.get("prompt") in FORCED_PROMPTS:
            p = r.get("p_value")
            return float(p) if p is not None and p == p else float("nan")
    return float("nan")


def load_cells() -> dict[tuple[str, str], dict]:
    sel: dict[tuple[str, str], dict] = {}
    for f in ordered_distinguish_files():
        d = _load(f)
        if not d:
            continue
        for a in d.get("aggregates", []):
            if not a.get("n_prompts") and not a.get("verdict_forced"):
                continue
            key = (a["model"], a["parameter"])
            sel[key] = {"file": f.name, "n": d.get("n_per_arm"), "a": a,
                        "forced_p": forced_p(d, a["model"], a["parameter"])
                        if a["parameter"] in PENALTIES else float("nan")}
    # the same verdicts collect() reports, or nothing downstream is trustworthy
    for r in collect():
        for p in P8:
            if p not in r:
                continue
            a = sel[(r["model"], p)]["a"]
            mine = a.get("verdict_forced") or a["verdict"] if p in PENALTIES else a["verdict"]
            assert mine == r[p], (r["model"], p, mine, r[p])
    return sel


def models_in_order() -> list[dict]:
    """collect()'s rows: sorted by output price, unpriced last."""
    return [r for r in collect() if r["provider"] == "fireworks"]


def classification() -> dict[tuple[str, str], dict]:
    """gap.py's cell for every (model, parameter), keyed."""
    return {(c["model"], c["parameter"]): c for c in gap_cells()}


